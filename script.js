function handleForm(form) {
  form.addEventListener('submit', e => {
    e.preventDefault();
    const phone = form.querySelector('[name="phone"]').value;
    if (phone.replace(/\D/g, '').length < 10) {
      showToast(currentLang === 'kk' ? 'Телефон нөмірін дұрыс енгізіңіз' : 'Введите корректный номер телефона');
      return;
    }
    showToast(i18n[currentLang].toast_success);
    form.reset();
    if (modal.classList.contains('open')) {
      modal.classList.remove('open');
      document.body.style.overflow = '';
    }
  });
}
handleForm(document.getElementById('contact-form'));
handleForm(document.getElementById('modal-form'));

document.querySelectorAll('input[type="tel"]').forEach(input => {
  input.addEventListener('input', () => {
    let v = input.value.replace(/\D/g, '');
    if (v.startsWith('8')) v = '7' + v.slice(1);
    if (!v.startsWith('7') && v.length > 0) v = '7' + v;
    let formatted = '+7';
    if (v.length > 1) formatted += ' (' + v.slice(1, 4);
    if (v.length >= 4) formatted += ') ' + v.slice(4, 7);
    if (v.length >= 7) formatted += '-' + v.slice(7, 9);
    if (v.length >= 9) formatted += '-' + v.slice(9, 11);
    input.value = formatted;
  });
});

