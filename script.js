/* Cartoon story autoplay */
(function() {
  const scenes = document.querySelectorAll('.cartoon-scene');
  const dots = document.querySelectorAll('.cartoon-dot');
  const bar = document.getElementById('cartoonBar');
  if (!scenes.length) return;
  let i = 0;
  const total = scenes.length;
  const DURATION = 5000;

  function go(n) {
    scenes[i].classList.remove('active');
    if (dots[i]) dots[i].classList.remove('active');
    i = ((n % total) + total) % total;
    scenes[i].classList.add('active');
    if (dots[i]) dots[i].classList.add('active');
    if (bar) bar.style.width = ((i + 1) / total * 100) + '%';
  }

  dots.forEach(d => d.addEventListener('click', () => {
    go(+d.dataset.i);
    reset();
  }));

  let timer = setInterval(() => go(i + 1), DURATION);
  function reset() {
    clearInterval(timer);
    timer = setInterval(() => go(i + 1), DURATION);
  }
  if (bar) bar.style.width = (100 / total) + '%';
})();
